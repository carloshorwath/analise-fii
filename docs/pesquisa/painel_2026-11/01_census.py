from common import *
pd.set_option('display.width',250); pd.set_option('display.max_rows',400)
c=conn()
m=tick_cnpj(c)
print("ticker->cnpj:",len(m),"cnpj unicos",m.cnpj.nunique())
t=pd.read_sql("select ticker,cnpj from tickers",c); u=pd.read_sql("select ticker,cnpj from universo",c)
j=t.merge(u,on='ticker'); print("conflito cnpj tickers vs universo:",(j.cnpj_x!=j.cnpj_y).sum(),"de",len(j))
p=pd.read_sql("select ticker,data,fechamento,fechamento_aj,volume from precos_diarios where fechamento is not null",c,parse_dates=['data'])
print("linhas validas",len(p))
cen=p.groupby('ticker').agg(primeiro=('data','min'),ultimo=('data','max'),n_pregoes=('data','count'))
r=pd.read_sql("select cnpj,data_referencia,data_entrega from relatorios_mensais",c,parse_dates=['data_referencia','data_entrega'])
rr=r.merge(m,on='cnpj').groupby('ticker').agg(n_informes=('data_referencia','count'),inf_primeiro=('data_referencia','min'),inf_ultimo=('data_referencia','max'),entr_primeiro=('data_entrega','min'))
cen=cen.join(rr,how='left')
cen['em_universo']=cen.index.isin(u.ticker)
cen.to_csv(os.path.join(OUT,'censo_por_ticker.csv'))
print(cen.describe(include='all').T)
print("sem informe:",cen.n_informes.isna().sum(), list(cen[cen.n_informes.isna()].index))
print("ultimo preco < 2026-11-01:"); print(cen[cen.ultimo<'2026-11-01'])
print("n_pregoes<505:",(cen.n_pregoes<505).sum()); print(cen[cen.n_pregoes<505].index.tolist())
print("primeiro preco por ano:"); print(cen.primeiro.dt.year.value_counts().sort_index())
# queda >40% em dia
p=p.sort_values(['ticker','data']); p['r']=p.groupby('ticker').fechamento.pct_change(); p['raj']=p.groupby('ticker').fechamento_aj.pct_change()
print("quedas > 40% em 1 dia (fechamento):"); print(p[p.r<-0.4][['ticker','data','fechamento','r','raj']])
print("quedas>40% raj:"); print(p[p.raj<-0.4][['ticker','data','r','raj']])
print("altas>60% :"); print(p[p.r>0.6][['ticker','data','r','raj']])
print("gaps de calendario > 10 dias com preco:"); 
p['gap']=p.groupby('ticker').data.diff().dt.days; print(p[p.gap>10][['ticker','data','gap']].head(30), (p.gap>10).sum())
print("divs:",pd.read_sql("select count(*),min(data_com),max(data_com),count(distinct ticker) from dividendos",c))
